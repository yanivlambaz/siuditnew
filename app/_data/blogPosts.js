export function buildAllBlogPosts() {
  const baseDate = new Date("2024-09-01");
  return TOPICS.map((t, i) => {
    const published = new Date(baseDate);
    published.setDate(published.getDate() + i * 11);
    const slug = t.slug;
    const metaTitle = `${t.title} | מדריך סיעוד פרימיום`;
    const metaDescription = `מדריך מלא: ${t.kw.join(", ")}. תוכן מקצועי לאחות פרטית, אחות לבית ואחות לבית חולים. שירות בכל הארץ 24/7.`;
    const sections = [
      { h2: "הרקע והצורך", paragraphs: paragraphsForTopic(t, i).slice(0, 2) },
      { h2: "איך נבנית תוכנית טיפול בפועל", paragraphs: paragraphsForTopic(t, i).slice(2, 4) },
      { h2: "מימון, ביטוח והמשך דרך", paragraphs: paragraphsForTopic(t, i).slice(4, 6) },
      { h2: "סיכום ושאלות נפוצות", paragraphs: [`להלן תשובות קצרות לשאלות נפוצות על הנושא. לייעוץ ממוקד למקרה שלכם השאירו פרטים באתר או צרו בוואטסאפ — נחזור תוך דקות.`] },
    ];
    return {
      slug,
      title: t.title,
      metaTitle,
      metaDescription,
      published: published.toISOString().slice(0, 10),
      updated: "2026-05-01",
      readMinutes: 10 + (i % 5),
      intro: paragraphsForTopic(t, i)[0],
      sections,
      faq: faqForTopic(t),
      relatedServiceSlugs: ["private-nurse-home", "private-nurse-hospital", "post-surgery-nurse", "elderly-care-nurse"].slice(
        0,
        3 + (i % 2),
      ),
      relatedCitySlugs: ["tel-aviv", "jerusalem", "haifa", "beer-sheva", "netanya"],
    };
  });
}

export const blogPosts = buildAllBlogPosts();

export function postBySlug(slug) {
  return blogPosts.find((p) => p.slug === slug);
}

export function relatedPostsForSlug(slug, n = 3) {
  const ix = blogPosts.findIndex((p) => p.slug === slug);
  if (ix < 0) return blogPosts.slice(0, n);
  const out = [];
  for (let j = 1; j <= blogPosts.length && out.length < n; j++) {
    out.push(blogPosts[(ix + j) % blogPosts.length]);
  }
  return out;
}

/** @param {string} citySlug */
export function relatedPostsForCity(citySlug) {
  const mod = [...citySlug].reduce((a, ch) => a + ch.charCodeAt(0), 0);
  if (!blogPosts.length) return [];
  const start = mod % blogPosts.length;
  const out = [];
  for (let k = 0; k < 3; k++) {
    out.push(blogPosts[(start + k) % blogPosts.length]);
  }
  return out;
}
