function PolicyCard({ id, title, children }) {
  return (
    <section
      id={id}
      className="scroll-mt-28 rounded-[1.75rem] border border-slate-200/85 bg-white/90 p-6 shadow-[0_1px_2px_rgba(15,23,42,0.04),0_14px_36px_-20px_rgba(15,23,42,0.12)] ring-1 ring-slate-100/80 sm:p-8"
    >
      {title ? (
        <h2 className="text-balance border-e-4 border-[#1f6bff] pe-4 text-xl font-extrabold tracking-tight text-[#0a1f44] sm:text-[1.35rem]">
          {title}
        </h2>
      ) : null}
      <div className={title ? "mt-5 space-y-4" : "space-y-4"}>{children}</div>
    </section>
  );
}

function P({ children, className = "" }) {
  return (
    <p className={["text-pretty text-[15px] leading-[1.85] text-slate-700", className].filter(Boolean).join(" ")}>
      {children}
    </p>
  );
}

function Ul({ items }) {
  return (
    <ul className="list-inside list-disc space-y-2 ps-1 text-[15px] leading-[1.8] text-slate-700 marker:text-[#1f6bff]">
      {items.map((t, i) => (
        <li key={i} className="ps-1">
          {t}
        </li>
      ))}
    </ul>
  );
}

