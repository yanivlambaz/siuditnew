/**
 * City guide + FAQ — editorial tone, fewer repeated keywords, clearer clinical boundaries.
 * @param {import('../_data/cities.js').City} city
 */
export function buildCitySeoSections(city) {
  const hospitalLine =
    city.hospitals?.length > 0
      ? city.hospitals.slice(0, 5).join(" · ")
      : "בתי החולים המרכזיים באזור";
  const hoodLine =
    city.neighborhoods?.length > 0
      ? city.neighborhoods.slice(0, 8).join(" · ")
      : "כל שכונות העיר";
  const valuesUl = city.valuePoints ?? [];

  return [
    {
      h2: `למה משפחות ב${city.name} מזמינות אחות פרטית — ומתי זה באמת נחוץ?`,
      paragraphs: [
        city.intro,
        `במהלך שגרה ב${city.name} (${city.region}) הרבה פעמים אין «רגע מודרך»: שחרור עם פוסט-אופ מבולגן, קשיש שמתקשה בנשימה בלילה, או בן משפחה שפשוט רוצה מישהו מוסמך שיקרא נכון את דף שחרור וידע מתי להתעקש לדבר עם רופא. אחות מוסמכת לא מחליפה גורם מטפל — אבל היא מונעת טעויות יקרות בתרופות, מזהה סימני אזהרה מוקדמים, ומחזיקה את הבית רגוע יותר כשהכל נראה «גדול מידי».`,
        `מסביב ל${hospitalLine} מתקבלות החלטות במהירות: אשפוזים קצרים יותר, יותר הוראות בית, ויותר אחריות על המשפחה בבית. ליווי קליני עוזר לסגור את הפער בין מה שנאמר במסדרון לבין מה שקורה במציאות — במיוחד כשאין כוח להסביר פעמיים לאותו אדם. ${city.localContext}`,
        `שירות טוב ב${city.name} גם מכבד לוגיסטיקה מקומית: זמני הגעה, חניה, גישה נכונה לבניין — כדי שהמטופל לא ישלם במחיר של עצבים. אנחנו מתכננים לפי השטח, לא לפי מפה גנרית.`,
      ],
    },
    {
      h2: `מה אחות פרטית עושה בפועל ב${city.name}? (תרחישים אמיתיים, בלי הבטחות מיותרות)`,
      paragraphs: [
        `אחרי ניתוח או פרוצדורה: ניטור כאב, שינוי הגייני בפצע לפי הוראה, מעקב אחר סימנים חיוניים לפי תדריך, ודיווח כשמשהו חורג מטווח סביר. בבית חולים: עזרה להבין מה עושים עם הנוזלים/תרופות, ליווי בשעות בהן המחלקה עמוסה, ותיעוד קצר שמסייע למשפחה לדבר באותה שפה עם הצוות.`,
        `בשגרת קשישות או דמנציה הדגש הוא בטיחות וכבוד: מניעת נפילות, היגיינה בלי השפלה, והדרכת בני משפחה איך «לא להילחם» על דברים קטנים כשיש סכנה. במצבים כרוניים (למשל אי-ספיקת לב, COPD, סוכרת עם תרופות מרובות) המשמעות היא מעקב תצפיתי ומדויק — לא «טיפול מרחוק» ולא הבטחה לקסמים.`,
        `אנחנו מכסים את ריכוזי העיקר בעיר — ${hoodLine}. לכל שיבוץ מתאימים רקע קליני רלוונטי (שיקום, ילדים, אשפוז יום, ניסיון בטיפול תומך/פליאטיבי כשצריך) ושפת דיבור שנוחה למשפחה.`,
      ],
    },
    {
      h2: `איך נראה תיאום מהיר ב${city.name} — בלי בלגן ובלי הפתעות`,
      paragraphs: [
        `בשיחה ראשונה נאסוף תמונה רפואית ברורה: אבחנות עיקריות, תרופות (כולל PRN), רגישויות, רופא מטפל, ומה בדיוק גורם הכי הרבה חשש בבית. נשאל גם לוגיסטיקה — קומה, נגישות, חניה, שעות שקט — כדי שהמשמרת הראשונה תהיה ממוקדת ולא ארוכה של ניחושים.`,
        `בתרחיש רגיל ב${city.name} רוב הפניות מקבלות מענה תוך דקות, ולרוב אפשר לקבוע משמרת ראשונה תוך שעות, כולל לילה וסופ״ש כשדחיפות גבוהה. במצב חירום רפואי — מד״א או מיון; אנחנו מתמקדים בהמשכיות אחרי שיש יציבות והנחיות.`,
        `כשיש תאריך שחרור, בונים «קו זמן»: מי מקבל בבית, מה נכנס ברכב, מה חייב להיות כתוב בבירור, ומי עונה על שאלות בלילה. זה הקטן שמפחית טעויות יקרות — במיוחד אחרי יום ארוך במחלקה.`,
      ],
    },
    {
      h2: `אמון, גבולות מקצועיים, ומה עדיין כדאי לשאול לפני התחלה`,
      paragraphs: [
        `בסיעודית אנחנו משבצים אחיות בעלות רישיון תקף של משרד הבריאות, ובוחנים ניסיון לפי סוג המקרה. אנחנו מפרידים בבירור בין מה שאחות עושה בהוראה לבין מה שדורש רופא — כדי שלא תישארו לבד עם שאלה רפואית אמיתית ב־02:00. ציטוט ממשפחה באזור: «${city.testimonialQuote}» (${city.testimonialAuthor}).`,
        `דברים שכדאי לשים לב אליהם כשבוחרים שירות ב${city.name}:`,
        ...valuesUl.map((v) => `• ${v}`),
        `אם זה נשמע סביר — דברו איתנו. נפרק את המקרה ביחד, נציע מסלול זמן הגיוני, ואם לא מתאים — נאמר זאת ביושר.`,
      ],
    },
  ];
}

/** @param {import('../_data/cities.js').City} city */
export function buildCityFaq(city) {
  const n = city.name;
  const hospSample =
    city.hospitals?.slice(0, 3).join(" · ") || "בתי החולים האזוריים";
  return [
    {
      q: `כמה מהר אפשר להתחיל עם אחות פרטית ב${n}?`,
      a: `ברוב המקרים אפשר לבנות תוכנית תוך דקות ולתאם משמרת ראשונה תוך שעות — בהתאם לזמינות ולמורכבות. במצבי חירום יש לפנות לחירום רפואי.`,
    },
    {
      q: `אפשר ליווי גם בבית חולים ב${n} — לא רק בבית?`,
      a: `כן. ליווי במחלקה אפשרי במשמרות גמישות, כולל לילה, כשצריך מענה צמוד או עזרה לתיאום מול הצוות.`,
    },
    {
      q: `מה ההבדל בין אחות מוסמכת לעובדת סיעוד ב${n}?`,
      a: `אחות עם רישיון משרד הבריאות מוסמכת לפעולות קליניות מוגדרות לפי הוראת רופא (לפי המסגרת החוקית והמקצועית). עובדת סיעוד אינה תחליף לכך. לעיתים משלבים את שני התפקידים כשזה מתאים למצב.`,
    },
    {
      q: `כמה זה עולה — ואיך בונים הערכה בלי הפתעות?`,
      a: `המחיר תלוי בשעות (יום/לילה/חג), במורכבות הרפואית ובלוגיסטיקה. אחרי שיחה קצרה נותנים טווח או הצעה מדויקת, בהתאם למידע שסיפקתם.`,
    },
    {
      q: `עם אילו בתי חולים באזור ${n} בדרך כלל מתאמים המשכיות?`,
      a: `אנחנו מתרגלים לתאם שחרור והמשכיות מול בתי החולים שמשרתים את תושבי ${n} — כולל ${hospSample}.`,
    },
    {
      q: `האם זה מתאים לקשישים ולמצבים כרוניים ב${n}?`,
      a: `כן — במיוחד כשרוצים בטיחות, צמצום אשפוזים חוזרים, וניהול תרופות בבית. החלטות רפואיות נשארות בידי הרופא; האחות מסייעת בביצוע ובתצפית.`,
    },
    {
      q: `איך בודקים שהאחות מוסמכת — ומה קורה אם משהו מרגיש לא נכון?`,
      a: `השיבוץ נעשה לאחר בחינת רישוי תקף והתאמת ניסיון למקרה. אם יש סימני אזהרה או החמרה — פונים לגורם רפואי/חירום; אנחנו לא מחליפים הערכת רופא, אבל כן מקצרים את הדרך לקבל החלטה בטוחה.`,
    },
  ];
}
